"""`cargo test` runner.

Cargo has no stable machine-readable test output. ``--format json`` is a
nightly-only libtest flag and ``cargo test --message-format json`` describes the
*build*, not the tests. So this runner parses libtest's stable text output,
which has been the same two shapes for a decade:

    test gitignore::tests::ig_escaped_trailing_space ... ok
    test result: ok. 186 passed; 0 failed; 0 ignored; 0 measured; 0 filtered out

That is enough for everything the tool needs. ``cargo-nextest`` is preferred
when it happens to be installed, because it writes real JUnit XML, but it is
never required - the text parser is the default path and the one that is
exercised by the unit tests.

Three Rust-specific facts drive the rest of this module.

**Tests live inside source files.** The idiomatic Rust unit test is a
``#[cfg(test)] mod tests`` block at the bottom of the module it tests, so one
file is both the code under test and the test. That is handled by
:mod:`coretexa_verify.inline_tests`, which reverts such a file hunk by hunk and
leaves the test hunks at head. Without it, every Rust PR of this shape would
either destroy its own evidence or be unrunnable.

**Compile errors are the interesting failure.** Reverting a source file that a
new test calls into does not produce an assertion failure - it produces
``error[E0599]: no method named ...``. Detecting that as ``BUILD_ERROR`` (rather
than as a generic non-zero exit) is what makes ``GATE_HOLDS_BUILD`` mean "the
tests gate the presence of the new API".

**Ignored is skipped.** ``#[ignore]`` tests report as ``ignored``; they are
counted as skipped and therefore excluded from the executed count, so a
selection that is entirely ``#[ignore]``d can never produce a verdict.

Build artefacts
---------------

Like ``go test``, ``cargo test`` *is* the build: it compiles the crate and its
dependencies from source on every invocation and its fingerprint includes the
mtime and hash of each source file, so a reverted ``.rs`` file is recompiled
before the test binary is linked. ``build.rs`` output, ``include_str!`` data and
``CARGO_BIN_EXE_*`` binaries are all regenerated by that same invocation. There
is therefore no separate build step to re-run and no stale artefact a test could
read instead of the reverted source - :meth:`detect_build_step` returns None and
:meth:`artifact_risk` returns ``""`` as statements about cargo, not as gaps.

The price is time: a cold compile of a large crate is minutes, not seconds,
which is why :data:`DEFAULT_TIMEOUT` is deliberately generous and is surfaced in
the report.
"""

from __future__ import annotations

import os
import posixpath
import re
import shutil

from ..gitops import run
from ..models import Outcome, TestRunResult
from .base import DetectionContext, Runner

#: Compiling a real crate tree from cold is minutes. The default per-run timeout
#: is raised accordingly and is reported, so a TIMEOUT verdict is never mistaken
#: for a finding about the code.
DEFAULT_TIMEOUT = 900

#: `test some::path ... ok`
TEST_LINE = re.compile(
    r"^test\s+(?P<name>\S+?)(?:\s+-\s+should\s+panic)?\s+\.\.\.\s+(?P<status>ok|FAILED|ignored|"
    r"benchmarked)\b"
)
#: `test result: ok. 3 passed; 0 failed; 1 ignored; 0 measured; 0 filtered out`
RESULT_LINE = re.compile(
    r"^test result:\s+(?P<verdict>\w+)\.\s+(?P<passed>\d+)\s+passed;\s+(?P<failed>\d+)\s+failed;"
    r"\s+(?P<ignored>\d+)\s+ignored"
)
#: `error[E0599]: no method named ...` - a compile error, not a test failure.
RUSTC_CODED_ERROR = re.compile(r"^error\[(?P<code>E\d{4})\]:", re.MULTILINE)
#: A diagnostic with no error code, e.g. `error: expected one of ...`.
RUSTC_BARE_ERROR = re.compile(r"^error:\s*(?P<text>.*)$", re.MULTILINE)

#: Lines that are cargo/rustc *summarising* the errors above rather than
#: reporting a new one. Counting them inflates the error count by one per
#: crate, which was enough to make a hand-checked "8 E0599" read as 9.
ERROR_SUMMARY_FRAGMENTS = (
    "could not compile",
    "aborting due to",
    "build failed",
)


def _count_rustc_errors(blob: str) -> tuple[int, list[str]]:
    """``(error count, distinct error codes)`` for one cargo invocation.

    Coded diagnostics win when there are any: ``error[E0599]`` is one real
    problem, whereas ``error: could not compile `gtk4` due to 8 previous
    errors`` is cargo restating those same eight. Only when nothing carries a
    code do uncoded diagnostics get counted, and the summary lines are excluded
    either way.
    """
    coded = RUSTC_CODED_ERROR.findall(blob)
    if coded:
        return len(coded), sorted(set(coded))
    bare = [
        text
        for text in RUSTC_BARE_ERROR.findall(blob)
        if not any(fragment in text for fragment in ERROR_SUMMARY_FRAGMENTS)
    ]
    return len(bare), []

#: Cargo/rustc failures that happen before any test binary exists.
BUILD_FAILURE_MARKERS = (
    "could not compile",
    "aborting due to",
    "error: linking with",
    "failed to run custom build command",
    "error: failed to select a version",
    "error: no such command",
)

#: `#[test]`-ish attribute immediately above a `fn name(`.
RUST_TEST_FN = re.compile(
    r"#\[(?:[\w:]*\b(?:test|bench|rstest|test_case|proptest|quickcheck)\b)[^\]]*\]"
    r"(?P<between>(?:\s*(?:#\[[^\]]*\]|//[^\n]*)\s*)*)\s*"
    r"(?:pub\s+)?(?:async\s+)?(?:unsafe\s+)?fn\s+(?P<name>\w+)"
)

#: `mod name {` - used to build the `a::b::test_name` path libtest reports.
RUST_MOD = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+(\w+)\s*\{", re.MULTILINE)


