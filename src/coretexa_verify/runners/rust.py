def parse_cargo_test_text(
    stdout: str, exit_code: int, stderr: str = ""
) -> TestRunResult:
    """Parse stable ``cargo test`` output into a :class:`TestRunResult`.

    Compile errors are checked *first and separately* from the test counts. A
    crate that does not compile prints ``error[E0599]`` to stderr and produces
    no ``test result:`` line at all; if we looked only at counts we would see
    zero of everything and call it ``NO_TESTS_RUN``, which reads as "nothing to
    say" when the truth is "the tests could not be built without the change" -
    the strongest gate signal there is.
    """
    blob = (stdout or "") + "\n" + (stderr or "")

    passed = failed = ignored = 0
    failing: list[str] = []
    saw_result_line = False

    for line in blob.splitlines():
        line = line.strip()
        m = TEST_LINE.match(line)
        if m:
            if m.group("status") == "FAILED":
                failing.append(m.group("name"))
            continue
        m = RESULT_LINE.match(line)
        if m:
            saw_result_line = True
            passed += int(m.group("passed"))
            failed += int(m.group("failed"))
            ignored += int(m.group("ignored"))

    n_errors, codes = _count_rustc_errors(blob)
    marker = next((m for m in BUILD_FAILURE_MARKERS if m in blob), "")

    # A compile failure before any test binary ran: no `test result:` line was
    # produced, but rustc had things to say. This is the gtk4-rs shape - revert
    # the source, keep the test, get eight E0599s.
    if not saw_result_line and (n_errors or marker):
        detail = f" ({n_errors} rustc error(s)"
        if codes:
            detail += ": " + ", ".join(codes[:6])
        detail += ")"
        return TestRunResult(
            command=[],
            outcome=Outcome.BUILD_ERROR,
            exit_code=exit_code,
            errored=max(n_errors, 1),
            total=max(n_errors, 1),
            erroring_ids=[c for c in codes[:50]] or ["<compile error>"],
            note=(
                f"the crate did not compile, so no test binary was produced and no assertion "
                f"was exercised{detail}"
                + (f"; {marker}" if marker else "")
            ),
        )

    if not saw_result_line:
        if exit_code == 0:
            return TestRunResult(
                command=[], outcome=Outcome.NO_TESTS_RUN, exit_code=exit_code,
                note="cargo test produced no `test result:` line and no error",
            )
        return TestRunResult(
            command=[], outcome=Outcome.RUNNER_ERROR, exit_code=exit_code,
            note=f"cargo test exited {exit_code} without producing a parseable test summary",
        )

    total = passed + failed + ignored
    if total == 0:
        return TestRunResult(
            command=[], outcome=Outcome.NO_TESTS_RUN, exit_code=exit_code,
            note="cargo test ran but the filter matched no tests",
        )

    if failed:
        outcome, note = Outcome.ASSERT_FAIL, ""
    elif n_errors or marker:
        # Some binaries ran and some crate failed to build: report the build
        # break, because a partial run cannot be called a pass.
        outcome = Outcome.BUILD_ERROR
        note = f"some tests ran but the build also reported {n_errors} rustc error(s)"
    elif exit_code == 0:
        outcome, note = Outcome.PASS, ""
    else:
        outcome = Outcome.RUNNER_ERROR
        note = f"all reported tests passed but cargo exited {exit_code}"

    return TestRunResult(
        command=[],
        outcome=outcome,
        exit_code=exit_code,
        passed=passed,
        failed=failed,
        errored=0,
        # `#[ignore]` is Rust's skip. Excluded from `executed`, so a selection
        # that is entirely ignored can never back a verdict.
        skipped=ignored,
        total=total,
        failing_ids=failing[:50],
        note=note,
    )


