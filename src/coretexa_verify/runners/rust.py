def detect_rust(ctx: DetectionContext, extra_args=None) -> Runner | None:
    """Pick the cargo runner, or return None if this is not a cargo project."""
    if not ctx.exists("Cargo.toml"):
        return None
    if not shutil.which("cargo"):
        return None

    manifest = ctx.read("Cargo.toml")
    shape = "workspace" if is_workspace_root(manifest) else "package"
    nextest = bool(shutil.which("cargo-nextest"))
    reason = (
        f"found Cargo.toml ({shape}) -> `cargo test --no-fail-fast`"
        + ("; cargo-nextest is installed but the stable text parser is used by default" if nextest else "")
    )
    runner = CargoTestRunner(ctx.repo, reason=reason, extra_args=extra_args, nextest=nextest)
    runner.setup_warnings.append(
        f"cargo compiles the crate and its dependencies on every test run, so each of the "
        f"runs this tool performs can take minutes from cold; the per-run timeout is "
        f"{DEFAULT_TIMEOUT}s by default and a TIMEOUT is reported as INCONCLUSIVE, never as a "
        f"finding"
    )
    return runner
