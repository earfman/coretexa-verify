class CargoTestRunner(Runner):
    """`cargo test --no-fail-fast`, scoped to the crate that owns the change.

    Target spelling (the runner owns it end to end):

    * ``ignore``                       - the whole crate's tests
    * ``ignore#gitignore_skip_bom``    - one integration binary (``tests/*.rs``)
    * ``ignore::gitignore::tests::foo``- one lib test, by libtest filter
    * ``ignore#bin::case``             - one test inside one integration binary

    ``::`` marks a narrowed target, which is the convention verify.py uses to
    decide what counts as running "a whole file or directory" - so cargo gets
    the same max-targets accounting as pytest for free.
    """

    id = "cargo-test"
    language = "rust"
    test_file_extensions = (".rs",)
    report_suffix = "xml"

    def __init__(self, repo: str, reason: str, extra_args=None, nextest: bool = False):
        super().__init__(repo, reason, extra_args)
        self.nextest = nextest

    # -- target parsing ----------------------------------------------------
    @staticmethod
    def _parse_target(target: str) -> tuple[str, str, str]:
        """``crate``, ``integration binary or ""``, ``libtest filter or ""``."""
        head, sep, filt = target.partition("::")
        crate, hsep, binary = head.partition("#")
        return crate, (binary if hsep else ""), (filt if sep else "")

    def build_command(self, targets: list[str], report_path: str) -> list[str]:
        crates: list[str] = []
        binaries: list[str] = []
        filters: list[str] = []
        for target in targets:
            crate, binary, filt = self._parse_target(target)
            if crate and crate not in crates:
                crates.append(crate)
            if binary and binary not in binaries:
                binaries.append(binary)
            if filt and filt not in filters:
                filters.append(filt)

        argv = ["cargo", "test", "--no-fail-fast"]
        for crate in crates:
            argv += ["-p", crate]
        for binary in binaries:
            argv += ["--test", binary]
        argv += self.extra_args

        # libtest accepts several positional filters (they are OR-ed) and
        # `--exact` makes each one match a whole test path rather than a
        # substring. Passing the names unanchored would let `foo` also select
        # `foo_regression`, which would quietly widen the very selection we
        # went to the trouble of narrowing.
        if filters:
            argv += ["--", "--exact", *filters]
        return argv

    def parse(self, report_path: str, exit_code: int, stdout: str, stderr: str) -> TestRunResult:
        return parse_cargo_test_text(stdout, exit_code, stderr)

    def default_test_dir(self) -> str | None:
        return None

    def subprocess_env(self) -> dict:
        env = super().subprocess_env()
        # Colour codes would break the line regexes; cargo honours this even
        # when something downstream thinks it is on a tty.
        env["CARGO_TERM_COLOR"] = "never"
        env["RUST_BACKTRACE"] = "0"
        return env

    # -- build artefacts ---------------------------------------------------
    def detect_build_step(self, timeout: int) -> None:
        """None: ``cargo test`` compiles the crate itself. See the module docstring."""
        return None

    def artifact_risk(self, targets: list[str], source_paths: list[str]) -> str:
        """Empty: cargo rebuilds from source on every ``cargo test``."""
        return ""

    # -- path -> crate spec ------------------------------------------------
    def focus(self, targets: list[str]) -> tuple[list[str], str] | None:
        """Turn repo-relative file paths into cargo crate specs.

        ``-p <crate>`` is used rather than changing directory, so a workspace
        member is addressed the same way whether the repository is a workspace
        or a single crate, and ``cwd`` stays at the manifest root where the
        lockfile lives.
        """
        out: list[str] = []
        crates: list[str] = []
        mapped = False
        for target in targets:
            path, sep, filt = target.partition("::")
            if "/" not in path and not path.endswith(".rs"):
                if target not in out:
                    out.append(target)
                continue
            mapped = True
            owner = owning_manifest(self.repo, path)
            manifest = os.path.join(self.repo, owner, "Cargo.toml") if owner else os.path.join(self.repo, "Cargo.toml")
            name = crate_name(_read(manifest))
            if not name:
                return None
            if name not in crates:
                crates.append(name)
            rel = posixpath.relpath(path, owner) if owner else path
            if rel.startswith("tests/") and rel.endswith(".rs"):
                spec = f"{name}#{posixpath.basename(rel)[:-3]}"
            else:
                spec = name
            if sep and filt:
                spec = f"{spec}::{filt}"
            if spec not in out:
                out.append(spec)
        if not mapped:
            return None
        return out, (
            f"cargo selects tests by crate, not by path, so the changed file(s) were mapped to "
            f"the nearest owning Cargo.toml and run with -p {' -p '.join(crates)}"
        )

    # -- enumeration -------------------------------------------------------
    def collect(self, targets: list[str], timeout: int, extra=None) -> list[str] | None:
        """``cargo test -- --list``. Returns None when the compile is too slow.

        Enumeration costs a full compile, which for a large crate exceeds the
        (deliberately short) refinement timeout. Returning None then switches
        selection refinement off rather than blocking the run - narrowing for
        Rust comes from :meth:`narrow_from_diff`, which needs no compile.
        """
        if any("/" in t or t.endswith(".rs") for t in targets):
            # Still in file-path space: focus() has not run yet, so there is no
            # crate to name. Burning a full compile on a command cargo would
            # reject helps nobody.
            return None
        crates: list[str] = []
        for target in targets:
            crate, _, _ = self._parse_target(target)
            if crate and crate not in crates:
                crates.append(crate)
        if not crates:
            return None
        argv = ["cargo", "test", "--no-fail-fast"]
        for crate in crates:
            argv += ["-p", crate]
        argv += ["--", "--list"]
        res = run(argv, cwd=self.cwd, timeout=timeout, env=self.subprocess_env(), isolate=True)
        if res.timed_out or res.returncode != 0:
            return None
        ids: list[str] = []
        for line in res.stdout.splitlines():
            line = line.strip()
            if line.endswith(": test") or line.endswith(": benchmark"):
                name = line.rsplit(":", 1)[0].strip()
                nid = f"{crates[0]}::{name}"
                if nid not in ids:
                    ids.append(nid)
        return ids or None

    # -- narrowing ---------------------------------------------------------
    def narrow_from_diff(self, repo, base_sha, head_sha, path, targets):
        """Keep only the ``#[test]`` functions whose body the diff touched."""
        if not path.endswith(".rs"):
            return None
        from .. import refine
        from ..hunks import read_head_text

        from ..inline_tests import find_regions

        head_text = read_head_text(repo, head_sha, path)
        if not head_text:
            return None
        changed = refine.changed_line_numbers(repo, base_sha, head_sha, path)
        if not changed:
            return None

        # A macro that generates tests makes narrowing unsafe - see
        # region_generates_tests_by_macro. Decline rather than measure a subset
        # we cannot show is the whole of what the PR added.
        regions = find_regions(path, head_text) or [(1, head_text.count("\n") + 1)]
        macro = region_generates_tests_by_macro(head_text, regions)
        if macro:
            return None

        spans = find_test_spans(head_text)
        if not spans:
            return None
        hit = [
            (name, full)
            for name, full, start, end in spans
            if changed & set(range(start, end + 1))
        ]
        if not hit or len(hit) == len(spans):
            # None of them, or all of them: narrowing would add nothing.
            return None

        # libtest reports `<file's module path>::<in-file module path>::<fn>`.
        owner = owning_manifest(repo, path)
        rel = posixpath.relpath(path, owner) if owner else path
        prefix = module_prefix(rel)
        qualified = [(name, f"{prefix}::{full}" if prefix else full) for name, full in hit]

        out = []
        for target in targets:
            base = target.partition("::")[0]
            for _, full in qualified:
                nid = f"{base}::{full}"
                if nid not in out:
                    out.append(nid)
        hit = qualified
        names = [name for name, _ in hit]
        return (
            out,
            f"only the {len(hit)} test function(s) this PR added or modified "
            f"({', '.join(names[:5])})",
            (
                f"the changed lines of {path} fall inside these #[test] fn declarations in the "
                f"head revision, and cargo was narrowed to them with "
                f"`-- --exact {' '.join(full for _, full in hit[:3])}`"
            ),
        )


