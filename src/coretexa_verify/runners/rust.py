def rust_test_paths(text: str) -> list[tuple[str, str, int]]:
    """``(bare name, module path, line)`` for each ``#[test]`` function.

    libtest reports a unit test as ``module::path::fn_name``, so the enclosing
    ``mod`` chain has to be reconstructed to build a filter that matches. The
    brace tracking reuses the same code-aware scanner the inline-test region
    finder uses, so braces inside strings and comments do not shift the chain.
    """
    from ..inline_tests import code_mask

    mask = code_mask(text)
    # depth -> module name entered at that depth
    stack: list[tuple[int, str]] = []
    depth = 0
    out: list[tuple[str, str, int]] = []

    mod_at: dict[int, str] = {}
    for m in RUST_MOD.finditer(text):
        if mask[m.start()]:
            mod_at[m.end() - 1] = m.group(1)  # index of the `{`

    test_at: dict[int, str] = {}
    for m in RUST_TEST_FN.finditer(text):
        if mask[m.start()]:
            test_at[m.start()] = m.group("name")

    for i, ch in enumerate(text):
        if i in test_at:
            path = "::".join(name for _, name in stack)
            line = text.count("\n", 0, i) + 1
            out.append((test_at[i], f"{path}::{test_at[i]}" if path else test_at[i], line))
        if not mask[i]:
            continue
        if ch == "{":
            depth += 1
            if i in mod_at:
                stack.append((depth, mod_at[i]))
        elif ch == "}":
            if stack and stack[-1][0] == depth:
                stack.pop()
            depth -= 1
    return out


def module_prefix(crate_relative_path: str) -> str:
    """The libtest module path a file's tests are reported under.

    libtest names a unit test ``<module path>::<fn>``, and a file's own module
    path comes from where it sits in the crate, not from anything written
    inside it. ``src/gitignore.rs`` contributes ``gitignore``; ``src/lib.rs``
    contributes nothing; ``src/a/mod.rs`` contributes ``a``. Getting this wrong
    is invisible - the filter simply matches no test and the run reports
    NO_TESTS_RUN - so it is worth spelling out.

    Integration tests under ``tests/`` are each their own crate root, so they
    have no prefix.
    """
    path = crate_relative_path.replace("\\", "/")
    if path.startswith(("tests/", "benches/", "examples/")):
        return ""
    if path.startswith("src/"):
        path = path[len("src/"):]
    if path in ("lib.rs", "main.rs"):
        return ""
    if path.endswith("/mod.rs"):
        path = path[: -len("/mod.rs")]
    elif path.endswith(".rs"):
        path = path[:-3]
    return path.replace("/", "::")


def find_test_spans(text: str) -> list[tuple[str, str, int, int]]:
    """``(name, module path, first line, last line)`` per ``#[test]`` function.

    The end of each function is found by matching its opening brace, not by
    running up to the next test. That distinction matters: anything between two
    test functions - a helper, a macro invocation that generates more tests -
    would otherwise be silently attributed to the test above it.
    """
    from ..inline_tests import _match_bracket, code_mask

    mask = code_mask(text)
    spans: list[tuple[str, str, int, int]] = []
    for name, full, start in rust_test_paths(text):
        offset = 0
        for _ in range(start - 1):
            offset = text.index("\n", offset) + 1
        brace = offset
        while brace < len(text) and not (mask[brace] and text[brace] == "{"):
            brace += 1
        end_off = _match_bracket(text, mask, brace, "{", "}") if brace < len(text) else -1
        end = text.count("\n", 0, end_off - 1) + 1 if end_off != -1 else start
        spans.append((name, full, start, max(end, start)))
    return spans


#: A macro invocation sitting where an item would go: `ignored!(...)`,
#: `glib::wrapper! { ... }`. Such a macro can expand to any number of
#: `#[test] fn`s whose names appear nowhere in the source.
ITEM_MACRO = re.compile(r"^\s*(?:pub\s+)?[a-z_]\w*(?:::\w+)*!\s*[\[({]")


def region_generates_tests_by_macro(text: str, regions: list[tuple[int, int]]) -> str:
    """The first item-position macro invocation inside a test region, or ``""``.

    A macro that expands into tests makes source-level narrowing unsafe: the
    generated test names are not in the file, so keeping "only the ``#[test]
    fn``s the diff touched" would quietly drop the very cases the PR added.
    ripgrep's gitignore tests are exactly this - ``ignored!(...)`` and
    ``not_ignored!(...)`` generate one test each - so the runner declines to
    narrow rather than measuring the wrong thing.
    """
    from ..inline_tests import code_mask

    mask = code_mask(text)
    lines = text.splitlines()
    offset = 0
    for idx, raw in enumerate(lines, start=1):
        line_start = offset
        offset += len(raw) + 1
        if not any(lo <= idx <= hi for lo, hi in regions):
            continue
        visible = "".join(
            raw[k] if line_start + k < len(mask) and mask[line_start + k] else " "
            for k in range(len(raw))
        )
        if ITEM_MACRO.match(visible):
            return visible.strip()
    return ""


