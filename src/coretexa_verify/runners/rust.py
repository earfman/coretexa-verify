def _read(path: str) -> str:
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            return fh.read(200_000)
    except OSError:
        return ""


def crate_name(manifest_text: str) -> str:
    """``name`` from the ``[package]`` table of a Cargo.toml, or ``""``.

    Parsed with a small line scan rather than a TOML library: this tool has no
    runtime dependencies and supports Python 3.9, where ``tomllib`` does not
    exist. Only the ``[package] name`` field is needed.
    """
    in_package = False
    for raw in manifest_text.splitlines():
        line = raw.strip()
        if line.startswith("["):
            in_package = line.replace(" ", "") == "[package]"
            continue
        if not in_package or "=" not in line or line.startswith("#"):
            continue
        key, _, value = line.partition("=")
        if key.strip() == "name":
            return value.strip().strip(",").strip().strip('"').strip("'")
    return ""


def is_workspace_root(manifest_text: str) -> bool:
    return any(line.strip().replace(" ", "") == "[workspace]" for line in manifest_text.splitlines())


def owning_manifest(repo: str, rel_path: str) -> str:
    """Nearest ancestor directory of ``rel_path`` with a package Cargo.toml.

    A virtual manifest (a ``[workspace]`` table with no ``[package]``) is not an
    owner - it declares members, it does not contain code - so the walk keeps
    going up past it only if it has no ``[package]`` of its own.
    """
    parts = rel_path.replace("\\", "/").split("/")[:-1]
    while parts:
        candidate = "/".join(parts)
        manifest = os.path.join(repo, candidate, "Cargo.toml")
        if os.path.exists(manifest) and crate_name(_read(manifest)):
            return candidate
        parts.pop()
    root = os.path.join(repo, "Cargo.toml")
    if os.path.exists(root) and crate_name(_read(root)):
        return ""
    return ""


